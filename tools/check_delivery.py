#!/usr/bin/env python3
"""Independently regenerate and replay complete RPX 11 case deliveries."""
import argparse, json, subprocess, tempfile, time
from pathlib import Path
from case_delivery import ROOT, load_optimization, sha, identity


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--case', action='append', required=True)
    ap.add_argument('--kernel', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args(); kernel = args.kernel.resolve(); output = args.out.resolve()
    assert not output.exists(), 'Preserve completed review receipts.'
    output.parent.mkdir(parents=True, exist_ok=True)
    inventory = json.loads((ROOT/'audit/corpus_inventory.json').read_text())
    report = {'status': 'RUNNING', 'reviewer': identity(__file__), 'helper': identity(ROOT/'tools/case_delivery.py'), 'kernel': identity(kernel), 'inventory': identity(ROOT/'audit/corpus_inventory.json'), 'scope': 'Actual models recanonicalized; every RPA regenerated byte-for-byte and each complete case certified as MI_OPT.', 'cases': []}
    start = time.perf_counter()
    def save(): output.with_suffix('.progress.json').write_text(json.dumps(report, indent=2)+'\n')
    def invoke(cmd):
        assert sha(kernel) == report['kernel']['sha256']
        before = time.perf_counter(); r = subprocess.run([str(kernel), *map(str, cmd)], cwd=ROOT, capture_output=True, text=True)
        result = {'command': [str(kernel), *map(str, cmd)], 'exit_code': r.returncode, 'seconds': time.perf_counter()-before, 'stdout': r.stdout, 'stderr': r.stderr}
        assert sha(kernel) == report['kernel']['sha256']
        return result
    for name in args.case:
        folder = ROOT/'cases'/name; receipt = folder/'preparation.json'; d = json.loads(receipt.read_text()); delivery = load_optimization(folder)
        case = {'case': name, 'status': 'RUNNING', 'receipt': identity(receipt), 'kind': 'two-block-certificate', 'artifacts': delivery['artifacts'], 'commands': [], 'pieces': []}; report['cases'].append(case); save()
        original = next(x for x in inventory['cases'] if x['case_id'] == name)
        for role, key in [('source', 'source_models'), ('target', 'final_target_models')]:
            assert sha(Path(d[role]['path'])) == d[role]['sha256'] == original[key][0]['sha256']
        with tempfile.TemporaryDirectory(prefix='rpx-complete-delivery-') as directory:
            tmp = Path(directory)
            for role in ('source', 'target'):
                result = invoke(['canonical', d[role]['path'], tmp/(role+'.mcm')]); case['commands'].append(result); save(); assert result['exit_code'] == 0, result
                assert sha(tmp/(role+'.mcm')) == delivery['artifacts'][role]['sha256']
            text=tmp/'proof.rpa';regenerated=tmp/'proof.rpx'
            result=invoke(['disassemble',delivery['proof'],text]);case['commands'].append(result);save();assert result['exit_code']==0,result
            if text.stat().st_size > 512*1024*1024:
                # Pretty RPA can exceed the path reader limit even for a valid
                # binary. Remove its header and insignificant line indentation
                # to use the separately bounded Certificate JSON compiler.
                compact=tmp/'certificate.json'
                with text.open('rb') as src, compact.open('wb') as dst:
                    assert src.readline()==b'RPA 11\n'
                    for line in src: dst.write(line.strip())
                command=['compile',compact,regenerated]
            else:
                command=['assemble',text,regenerated]
            result=invoke(command);case['commands'].append(result);save();assert result['exit_code']==0,result
            assert sha(regenerated)==sha(delivery['proof'])
            case['pieces'].append({'id':'complete','status':'ASSEMBLED','rpx_sha256':sha(regenerated)})
            result=invoke(['verify',tmp/'source.mcm',tmp/'target.mcm',regenerated])
            case['commands'].append(result); save(); assert result['exit_code'] == 0, result
            actual = json.loads(result['stdout'])
            assert actual['status'] == 'VERIFIED' and actual['guarantee'] == 'MI_OPT'
            case['verification'] = actual
        assert sha(receipt) == case['receipt']['sha256']
        for observed in delivery['artifacts'].values(): assert sha(Path(observed['path'])) == observed['sha256']
        case['status'] = 'PASS'; save(); print(name, 'PASS', len(case['pieces']), flush=True)
    report['status'] = 'PASS'; report['wall_seconds'] = time.perf_counter()-start
    output.write_text(json.dumps(report, indent=2)+'\n')


if __name__ == '__main__': main()
