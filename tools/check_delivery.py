#!/usr/bin/env python3
"""Independently regenerate and replay complete single/bundled case deliveries."""
import argparse, json, subprocess, tempfile, time
from pathlib import Path
from case_delivery import ROOT, load_delivery, sha, identity


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--case', action='append', required=True)
    ap.add_argument('--kernel', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args(); kernel = args.kernel.resolve(); output = args.out.resolve()
    assert not output.exists(), 'Preserve completed review receipts.'
    output.parent.mkdir(parents=True, exist_ok=True)
    inventory = json.loads((ROOT/'audit/corpus_inventory.json').read_text())
    report = {'status': 'RUNNING', 'reviewer': identity(__file__), 'helper': identity(ROOT/'tools/case_delivery.py'), 'kernel': identity(kernel), 'inventory': identity(ROOT/'audit/corpus_inventory.json'), 'scope': 'Actual models recanonicalized; every RPA regenerated byte-for-byte and each complete requested piece replayed. Original contract completeness requires separate semantic review.', 'cases': []}
    start = time.perf_counter()
    def save(): output.with_suffix('.progress.json').write_text(json.dumps(report, indent=2)+'\n')
    def invoke(cmd):
        assert sha(kernel) == report['kernel']['sha256']
        before = time.perf_counter(); r = subprocess.run([str(kernel), *map(str, cmd)], cwd=ROOT, capture_output=True, text=True)
        result = {'command': [str(kernel), *map(str, cmd)], 'exit_code': r.returncode, 'seconds': time.perf_counter()-before, 'stdout': r.stdout, 'stderr': r.stderr}
        assert sha(kernel) == report['kernel']['sha256']
        return result
    stable = lambda x: {k: v for k, v in x.items() if not k.endswith('_us')}
    for name in args.case:
        folder = ROOT/'cases'/name; receipt = folder/'preparation.json'; d = json.loads(receipt.read_text()); delivery = load_delivery(folder, d)
        case = {'case': name, 'status': 'RUNNING', 'receipt': identity(receipt), 'kind': delivery['kind'], 'artifacts': delivery['artifacts'], 'commands': [], 'pieces': []}; report['cases'].append(case); save()
        original = next(x for x in inventory['cases'] if x['case_id'] == name)
        for role, key in [('source', 'source_models'), ('target', 'final_target_models')]:
            assert sha(Path(d[role]['path'])) == d[role]['sha256'] == original[key][0]['sha256']
        with tempfile.TemporaryDirectory(prefix='rpx-complete-delivery-') as directory:
            tmp = Path(directory)
            for role in ('source', 'target'):
                result = invoke(['canonical', d[role]['path'], tmp/(role+'.mcm')]); case['commands'].append(result); save(); assert result['exit_code'] == 0, result
                assert sha(tmp/(role+'.mcm')) == delivery['artifacts'][role+'.mcm']['sha256']
            for piece in delivery['pieces']:
                regenerated = tmp/(piece['id']+'.rpx')
                result = invoke(['assemble', piece['rpa'], regenerated]); case['commands'].append(result); save(); assert result['exit_code'] == 0, result
                assert sha(regenerated) == sha(piece['rpx'])
                result = invoke(['verify', tmp/'source.mcm', tmp/'target.mcm', regenerated, piece['request']]); case['commands'].append(result); save(); assert result['exit_code'] == 0, result
                actual = json.loads(result['stdout']); assert actual['status'] == 'VERIFIED' and stable(actual) == stable(piece['result'])
                case['pieces'].append({'id': piece['id'], 'status': 'PASS', 'rpx_sha256': sha(regenerated), 'result': actual}); regenerated.unlink(); save()
        assert sha(receipt) == case['receipt']['sha256']
        for observed in delivery['artifacts'].values(): assert sha(Path(observed['path'])) == observed['sha256']
        case['status'] = 'PASS'; save(); print(name, 'PASS', len(case['pieces']), flush=True)
    report['status'] = 'PASS'; report['wall_seconds'] = time.perf_counter()-start
    output.write_text(json.dumps(report, indent=2)+'\n')


if __name__ == '__main__': main()
