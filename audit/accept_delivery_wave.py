#!/usr/bin/env python3
"""Independent byte-bound replay of the 78 submitted certificate contracts.

This checks the existing caller requests, not whether those requests exhaust the
claims in the original reports. The separate contract review covers that issue.
"""
import hashlib,json,subprocess,tempfile,time
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'audit/validation/delivery-acceptance-2026-10-11'
WAVE=ROOT/'audit/validation/wave-rpx-2026-10-11/run.json'
KERNEL=ROOT/'target/validation-wave-rpx-2026-10-11/release/rpx'

def sha(path):
    h=hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()

def semantic(value):
    return {k:v for k,v in value.items() if not k.endswith('_us')}

def main():
    OUT.mkdir(parents=True,exist_ok=True)
    assert not (OUT/'result.json').exists(),'Do not overwrite a completed audit.'
    start=time.perf_counter();wave=json.loads(WAVE.read_text());ledger_path=ROOT/'audit/acceptance.json'
    ledger=json.loads(ledger_path.read_text());selected=[x for x in ledger['cases'] if x['status']=='VERIFIED']
    expected={x['case']:x for x in wave['replayed']}
    assert len(selected)==78 and {x['case_id'] for x in selected}==set(expected)
    assert sha(KERNEL)==wave['kernel_sha256']
    for name,digest in wave['source_sha256'].items():assert sha(ROOT/name)==digest,name
    assert sha(ROOT/'Cargo.lock')==wave['lock_sha256']
    report={'status':'RUNNING','kernel':str(KERNEL),'kernel_sha256':sha(KERNEL),'ledger_sha256':sha(ledger_path),'wave_receipt_sha256':sha(WAVE),'scope':'Recanonicalize original full models, reassemble actual RPA and replay each submitted caller request. Complete-report-contract coverage is a separate review.','cases':[]}
    def save():(OUT/'progress.json').write_text(json.dumps(report,indent=2)+'\n')
    save()
    for entry in sorted(selected,key=lambda x:int(x['case_id'][4:])):
        name=entry['case_id'];case=ROOT/'cases'/name;prior=expected[name]
        row={'case':name,'status':'RUNNING','commands':[]};report['cases'].append(row)
        before={n:sha(case/n) for n in ['source.mcm','target.mcm','proof.rpa','proof.rpx','request.json']};row['artifacts']=before
        try:
            for n,digest in prior['artifacts'].items():assert before[n]==digest,(name,n,'submitted artifact changed')
            for which in ['source','target']:assert sha(Path(entry[which]['path']))==entry[which]['sha256'],(name,which,'actual model changed')
            with tempfile.TemporaryDirectory(prefix='rpx-delivery-') as directory:
                tmp=Path(directory)
                commands=[['canonical',entry['source']['path'],str(tmp/'source.mcm')],['canonical',entry['target']['path'],str(tmp/'target.mcm')],['assemble',str(case/'proof.rpa'),str(tmp/'proof.rpx')],['verify',str(tmp/'source.mcm'),str(tmp/'target.mcm'),str(tmp/'proof.rpx'),str(case/'request.json')]]
                for args in commands:
                    now=time.perf_counter();p=subprocess.run([str(KERNEL)]+args,capture_output=True,text=True)
                    r={'command':[str(KERNEL)]+args,'exit_code':p.returncode,'seconds':time.perf_counter()-now,'stdout':p.stdout,'stderr':p.stderr};row['commands'].append(r)
                    assert p.returncode==0,(name,args[0],p.stdout,p.stderr)
                    if args[0]=='verify':
                        result=json.loads(p.stdout);assert result['status']=='VERIFIED';assert semantic(result)==semantic(prior['result']),(name,'semantic statistics changed');row['result']=result
                for n in ['source.mcm','target.mcm','proof.rpx']:assert sha(tmp/n)==before[n],(name,n,'regenerated bytes differ')
            assert all(sha(case/n)==v for n,v in before.items()),(name,'artifact changed during audit')
            row['status']='PASS'
        except Exception as error:row['status']='FAIL';row['error']=repr(error)
        print(name,row['status'],flush=True);save()
    assert sha(KERNEL)==report['kernel_sha256']
    assert all(sha(ROOT/n)==h for n,h in wave['source_sha256'].items())
    report['status']='PASS' if all(c['status']=='PASS' for c in report['cases']) else 'FAIL'
    report['wall_seconds']=time.perf_counter()-start;report['passed']=sum(c['status']=='PASS' for c in report['cases']);report['functional_delivery_complete']=False
    (OUT/'result.json').write_text(json.dumps(report,indent=2)+'\n');print(report['status'],report['passed'],flush=True)
    raise SystemExit(0 if report['status']=='PASS' else 1)

if __name__=='__main__':main()
